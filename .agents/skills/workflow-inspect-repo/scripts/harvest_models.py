# ruff: ignore[implicit-namespace-package]
"""Data models and constants for agent skill harvesting."""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from pathlib import Path

# Directories to ignore during recursive filesystem traversal
IGNORE_DIRS: set[str] = {
    ".git",
    ".venv",
    "venv",
    ".tox",
    "node_modules",
    "build",
    "dist",
    "__pycache__",
    ".eggs",
    ".pytest_cache",
    ".ruff_cache",
    ".temp",
}

INSTRUCTION_FILENAMES = ("AGENTS.md", "CLAUDE.md", ".cursorrules", ".windsurfrules")

SKILL_RULE_SUFFIXES = {".mdc", ".md"}

PR_TEMPLATE_NAMES = ("PULL_REQUEST_TEMPLATE.md", "pull_request_template.md")

PR_AI_CHECKLIST_KEYWORDS = ("ai ", "ai-", "copilot", "llm", "generated by")


@dataclass(frozen=True)
class DiscoveredSkill:
    """Represents an agent skill found in a repository."""

    name: str
    location: str
    description: str = ""
    is_novel: bool = True
    triggers: list[str] = field(default_factory=list)
    scripts: list[str] = field(default_factory=list)
    kind: str = "skill"  # "skill", "cursor-rule", "mcp-server"


@dataclass(frozen=True)
class HarvestResult:
    """Consolidated harvest analysis of agent skills and instructions."""

    target_name: str
    target_path: Path
    instructions: list[str] = field(default_factory=list)
    instruction_symlinks: list[tuple[str, str]] = field(default_factory=list)
    novel_skills: list[DiscoveredSkill] = field(default_factory=list)
    shared_skills: list[DiscoveredSkill] = field(default_factory=list)
    mcp_servers: list[str] = field(default_factory=list)
    ai_policy_present: bool = False
    ai_pr_checklist_present: bool = False
    agent_directives: list[str] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)
